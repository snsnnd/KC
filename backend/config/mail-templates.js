// ================================================================
// 科创社 CMS — 邮件通知默认模板
// 本文件定义了审批流程中发送给用户的系统邮件默认模板。
// 占位符采用 {变量名} 格式，在发送前由 server.js 中的 mailFrom()
// 函数替换为实际值（如申请编号、申请人、审批意见等）。
// ================================================================

// --- 物资/经费使用申请 审批结果邮件模板 ---
// 适用于成员提交实验室物资、器材或经费使用申请后的审批通知。
// {领取提示}: 仅在批准时出现，指示领取方式（如"请前往实验室领取"）。
const defaultUsageMailTemplates = {
  // 批准通知 — 邮件主题
  approvedSubject: "[申请已批准] {申请编号} {申请对象}",
  // 批准通知 — 邮件正文（纯文本，支持 \n 换行）
  // 可用占位符: {申请人}, {申请类型}, {申请编号}, {申请对象},
  // {数量金额}, {用途}, {领取提示}, {审批意见}, {审批人}, {审批时间}
  approvedBody: "{申请人}，你好：\n\n你的{申请类型}申请已批准。\n申请编号：{申请编号}\n申请对象：{申请对象}\n数量/金额：{数量金额}\n用途：{用途}\n{领取提示}\n审批意见：{审批意见}\n审批人：{审批人}\n审批时间：{审批时间}\n",
  // 拒绝通知 — 邮件主题
  rejectedSubject: "[申请未批准] {申请编号} {申请对象}",
  // 拒绝通知 — 邮件正文
  // 与批准通知相比，不包含 {领取提示} 字段。
  rejectedBody: "{申请人}，你好：\n\n你的{申请类型}申请未批准。\n申请编号：{申请编号}\n申请对象：{申请对象}\n数量/金额：{数量金额}\n用途：{用途}\n审批意见：{审批意见}\n审批人：{审批人}\n审批时间：{审批时间}\n"
};

// --- 社团加入申请 审批结果邮件模板 ---
// 适用于用户提交加入社团申请后的审批通知。
// 注意：acceptedBody 末尾提示"后续账号开通信息将另行发送"，
// 这是与使用申请模板的主要区别。
const defaultApplicationMailTemplates = {
  // 通过通知 — 邮件主题
  acceptedSubject: "[加入申请已通过] {申请编号} {部门}",
  // 通过通知 — 邮件正文
  // 可用占位符: {申请人}, {申请编号}, {部门}, {审批意见}, {审批人}, {审批时间}
  acceptedBody: "{申请人}，你好：\n\n你的加入申请已通过审核。\n申请编号：{申请编号}\n申请部门：{部门}\n审批意见：{审批意见}\n审批人：{审批人}\n审批时间：{审批时间}\n\n后续账号开通信息将另行发送。\n",
  // 拒绝通知 — 邮件主题
  rejectedSubject: "[加入申请未通过] {申请编号} {部门}",
  // 拒绝通知 — 邮件正文
  rejectedBody: "{申请人}，你好：\n\n你的加入申请本次未通过审核。\n申请编号：{申请编号}\n申请部门：{部门}\n审批意见：{审批意见}\n审批人：{审批人}\n审批时间：{审批时间}\n"
};

export { defaultUsageMailTemplates, defaultApplicationMailTemplates };
